<p>Examiners also like a question that asks for the number of students who offer exactly two subjects. Add only the overlap-only regions: 6 + 4 + 3 = 13. Or at least two subjects, meaning the overlaps plus the middle: 13 + 3 = 16. The word exactly excludes the middle. The words at least include it.</p>
